<?php

namespace App\Console\Commands;

use App\Actions\Collections\MonthlyDues\GenerateMonthlyDues as GenerateMonthlyDuesAction;
use App\Queries\Collections\Settings\CollectionSettingsQuery;
use App\Utility\PeriodHelper;
use Illuminate\Console\Command;

/**
 * The other half of the generation mode: the scheduler raising a month's dues.
 *
 * The office generates a month by hand from the Monthly Dues Generator; when
 * the association bills **automatically** (Settings → Collections → Bill
 * Generation), nobody has to. This runs daily and, once the configured
 * generation day has arrived, raises the current month — the generator's own
 * rule, reached on its own, so a month is still only ever billed once (an
 * account already billed for it is skipped).
 *
 * It runs on the generation day and on every day after it, so a day the
 * scheduler was down costs nothing: the month is raised the next time the
 * command runs, and `CollectionSettingsQuery::dueDateFor()` starts that late
 * month's grace period from the day it is actually raised.
 */
class GenerateMonthlyDues extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'dues:generate-monthly';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Raise the current month\'s dues when the association bills automatically';

    /** @var CollectionSettingsQuery */
    private $settings;

    /** @var GenerateMonthlyDuesAction */
    private $dues;

    public function __construct(CollectionSettingsQuery $settings, GenerateMonthlyDuesAction $dues)
    {
        parent::__construct();

        $this->settings = $settings;
        $this->dues = $dues;
    }

    /**
     * Execute the console command.
     *
     * @return int
     */
    public function handle(): int
    {
        if (! $this->settings->generationMode()->isAutomatic()) {
            $this->info('Monthly dues are generated by the office — nothing to raise.');

            return 0;
        }

        $month = PeriodHelper::current();
        $generationDay = (int) $this->settings->get('generation_day', 1);

        if (now()->day < $generationDay) {
            $this->info('Generation day ' . $generationDay . ' has not arrived; nothing to raise for '
                . PeriodHelper::label($month) . ' yet.');

            return 0;
        }

        $result = $this->dues->handle($month);

        $this->info('Raised ' . $result['created'] . ' monthly due invoice(s) for ' . PeriodHelper::label($month)
            . ' (' . $result['skipped'] . ' already billed).');

        return 0;
    }
}
